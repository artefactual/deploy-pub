"""Merge the evidence bundles of a run into the checklist markdown, a summary and an index page.

Usage::

    python -m rt.report --evidence-dir evidence --out report [--base-url URL]

The checklist markdown follows the layout of the issue template generated by
``generate_issue_template.py`` in the testing-checklists repository, so it can
be pasted into a release testing issue with the boxes ticked by the run.
"""

from __future__ import annotations

import argparse
import html
import json
from collections import Counter
from pathlib import Path
from typing import Any

from rt.checklist import CHECKLIST_CSV, ChecklistItem, load_checklist

PASS = "pass"
FAIL = "fail"
KNOWN = "known"
PENDING = "pending"
NOT_RUN = "not run"

META_FIELDS = (("External tools", "external_tools"),)


def load_results(evidence_dir: Path) -> dict[str, dict[str, dict[str, Any]]]:
    """``os label -> item id -> result.json`` for every bundle below the directory."""
    results: dict[str, dict[str, dict[str, Any]]] = {}
    for path in sorted(evidence_dir.rglob("result.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        os_label = str(data.get("os_label") or path.parent.parent.name)
        item_id = str(data.get("item_id") or path.parent.name)
        data["_path"] = path
        data["_dir"] = path.parent
        results.setdefault(os_label, {})[item_id] = data
    return results


def _evidence_link(result: dict[str, Any], evidence_dir: Path, base_url: str | None) -> str:
    relative = Path(result["_dir"]).relative_to(evidence_dir).as_posix()
    if base_url:
        return f"{base_url.rstrip('/')}/{relative}/"
    return f"{relative}/"


def _warnings(result: dict[str, Any]) -> list[str]:
    return [str(warning) for warning in result.get("warnings", [])]


def _status_label(result: dict[str, Any]) -> str:
    """The status of a result, qualified when a passing scenario carries warnings."""
    status = str(result.get("status", NOT_RUN))
    warnings = _warnings(result)
    if status == PASS and warnings:
        return f"{status} with {len(warnings)} warning{'s' if len(warnings) != 1 else ''}"
    return status


def _needs_a_look(result: dict[str, Any]) -> bool:
    return result.get("status") in (FAIL, PENDING, NOT_RUN) or bool(_warnings(result))


def _sorted_ids(identifiers: Any) -> list[str]:
    return sorted(identifiers, key=lambda identifier: [int(part) for part in str(identifier).split(".")])


MESSAGE_LIMIT = 400


def _one_line(message: object) -> str:
    """A multi-line message as one line: the bullets of a list become a semicolon-separated run."""
    lines = [line.strip().removeprefix("- ").strip() for line in str(message or "").splitlines()]
    flat = "; ".join(line for line in lines if line)
    flat = flat.replace(":;", ":")
    return flat if len(flat) <= MESSAGE_LIMIT else flat[: MESSAGE_LIMIT - 1] + "…"


def _criterion_suffix(criterion: dict[str, Any]) -> str:
    outcome = str(criterion.get("outcome", NOT_RUN))
    message = _one_line(criterion.get("message", ""))
    if outcome == PASS:
        return ""
    if outcome == FAIL:
        return f" **FAILED** ({message})" if message else " **FAILED**"
    if outcome == KNOWN:
        return f" _known failure: {message}_" if message else " _known failure_"
    if outcome == PENDING:
        return f" _pending: {message}_" if message else " _pending_"
    return " _(not run)_"


def render_checklist(
    checklist: dict[str, ChecklistItem],
    results: dict[str, dict[str, Any]],
    os_label: str,
    evidence_dir: Path,
    base_url: str | None,
) -> str:
    lines: list[str] = [f"# Release testing: {os_label}", ""]
    versions = {str(result.get("versions", {}).get("archivematica", "")) for result in results.values()}
    versions.discard("")
    if versions:
        lines += [f"Archivematica {', '.join(sorted(versions))}; boxes ticked by the automated run.", ""]
    current_area: str | None = None
    for item in sorted(checklist.values(), key=lambda entry: entry.sort_key):
        if item.area != current_area:
            lines += [f"## {item.area}", ""]
            current_area = item.area
        lines += [f"### {item.id}", ""]
        for label, attribute in META_FIELDS:
            value = getattr(item, attribute)
            if value:
                lines += [f"**{label}**: {value}", ""]
        if item.feature:
            lines.append(item.feature)
        result = results.get(item.id)
        criteria = list(result.get("criteria", [])) if result else []
        for index, text in enumerate(item.criteria):
            if result is not None and index < len(criteria):
                criterion = criteria[index]
                mark = "x" if criterion.get("outcome") == PASS else " "
                lines.append(f"- [{mark}] {text}{_criterion_suffix(criterion)}")
            else:
                lines.append(f"- [ ] {text}")
        lines.extend(item.notes)
        if result is not None:
            link = _evidence_link(result, evidence_dir, base_url)
            error = _one_line(result.get("error"))
            detail = f"; error: {error}" if error else ""
            lines.append(f"_Automated run: {_status_label(result)}{detail}. Evidence: {link}_")
            lines.extend(f"- Warning: {warning}" for warning in _warnings(result))
        lines.append("")
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def render_summary(checklist: dict[str, ChecklistItem], results: dict[str, dict[str, dict[str, Any]]]) -> str:
    lines: list[str] = ["# Regression testing summary", ""]
    covered = {item_id for per_os in results.values() for item_id in per_os}
    lines.append("| Platform | Run | Passed | Failed | Known | Pending | Not run | With warnings |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for os_label, per_os in sorted(results.items()):
        counts = Counter(str(result.get("status", NOT_RUN)) for result in per_os.values())
        with_warnings = sum(1 for result in per_os.values() if _warnings(result))
        lines.append(
            f"| {os_label} | {len(per_os)} | {counts[PASS]} | {counts[FAIL]} | {counts[KNOWN]} | {counts[PENDING]} "
            f"| {counts[NOT_RUN]} | {with_warnings} |"
        )
    lines.append("")
    for os_label, per_os in sorted(results.items()):
        flagged = {item_id: result for item_id, result in per_os.items() if _needs_a_look(result)}
        if not flagged:
            continue
        lines += [f"## {os_label}: items that need a look", ""]
        for item_id in _sorted_ids(flagged):
            result = flagged[item_id]
            lines.append(f"- **{item_id}** {_status_label(result)}: {result.get('scenario', '')}")
            error = _one_line(result.get("error"))
            if error:
                lines.append(f"  - error: {error}")
            for criterion in result.get("criteria", []):
                if criterion.get("outcome") != PASS:
                    message = _one_line(criterion.get("message", ""))
                    lines.append(
                        f"  - {criterion.get('outcome')}: {criterion.get('text')}"
                        + (f" ({message})" if message else "")
                    )
            lines.extend(f"  - warning: {warning}" for warning in _warnings(result))
        lines.append("")
    for os_label, per_os in sorted(results.items()):
        known = {item_id: result for item_id, result in per_os.items() if result.get("status") == KNOWN}
        if not known:
            continue
        lines += [f"## {os_label}: known failures", ""]
        for item_id in _sorted_ids(known):
            result = known[item_id]
            lines.append(f"- **{item_id}** {result.get('scenario', '')}")
            for criterion in result.get("criteria", []):
                if criterion.get("outcome") == KNOWN:
                    lines.append(f"  - {criterion.get('text')} ({_one_line(criterion.get('message', ''))})")
        lines.append("")
    missing = [item_id for item_id in checklist if item_id not in covered]
    lines += [
        "## Coverage",
        "",
        f"{len(covered)} of {len(checklist)} checklist items have an automated result.",
    ]
    if missing:
        lines.append("Items without a result: " + ", ".join(missing))
    return "\n".join(lines) + "\n"


def render_index(
    checklist: dict[str, ChecklistItem],
    results: dict[str, dict[str, dict[str, Any]]],
    evidence_dir: Path,
    base_url: str | None,
) -> str:
    rows: list[str] = []
    for os_label, per_os in sorted(results.items()):
        for item_id in _sorted_ids(per_os):
            result = per_os[item_id]
            item = checklist.get(item_id)
            link = html.escape(_evidence_link(result, evidence_dir, base_url))
            attachments = " ".join(
                f'<a href="{link}{html.escape(str(path))}">{html.escape(str(label))}</a>'
                for label, path in sorted(result.get("attachments", {}).items())
            )
            rows.append(
                "<tr>"
                f"<td>{html.escape(os_label)}</td>"
                f'<td><a href="{link}result.json">{html.escape(item_id)}</a></td>'
                f"<td>{html.escape(item.area if item else '')}</td>"
                f'<td class="{html.escape(str(result.get("status", "")).replace(" ", "-"))}">'
                f"{html.escape(str(result.get('status', '')))}</td>"
                f"<td>{html.escape(str(result.get('scenario', '')))}</td>"
                f'<td class="{"warn" if _warnings(result) else ""}">{len(_warnings(result)) or ""}</td>'
                f"<td>{attachments}</td>"
                "</tr>"
            )
    return (
        '<!doctype html><meta charset="utf-8"><title>Regression testing results</title>'
        "<style>body{font-family:sans-serif;margin:2rem}table{border-collapse:collapse}"
        "td,th{border:1px solid #ccc;padding:.3rem .6rem;text-align:left}"
        "td.pass{background:#dff5e1}td.fail{background:#f8d7d5}td.pending{background:#fff1c2}td.known{background:#e5e7eb}"
        "td.warn{background:#fff1c2}</style>"
        "<h1>Regression testing results</h1>"
        "<table><tr><th>Platform</th><th>Item</th><th>Area</th><th>Status</th><th>Scenario</th>"
        "<th>Warnings</th><th>Evidence</th></tr>" + "".join(rows) + "</table>\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--evidence-dir", type=Path, required=True, help="directory holding the evidence bundles"
    )
    parser.add_argument(
        "--checklist", type=Path, default=CHECKLIST_CSV, help="checklist CSV (default: vendored copy)"
    )
    parser.add_argument("--out", type=Path, required=True, help="output directory")
    parser.add_argument("--base-url", default=None, help="URL where the evidence directory is published")
    args = parser.parse_args(argv)

    checklist = load_checklist(args.checklist)
    results = load_results(args.evidence_dir)
    args.out.mkdir(parents=True, exist_ok=True)
    for os_label, per_os in results.items():
        path = args.out / f"checklist-{os_label}.md"
        path.write_text(
            render_checklist(checklist, per_os, os_label, args.evidence_dir, args.base_url), encoding="utf-8"
        )
    summary = render_summary(checklist, results)
    (args.out / "summary.md").write_text(summary, encoding="utf-8")
    (args.out / "index.html").write_text(
        render_index(checklist, results, args.evidence_dir, args.base_url), encoding="utf-8"
    )
    merged = {
        os_label: {
            item_id: {key: value for key, value in result.items() if not key.startswith("_")}
            for item_id, result in per_os.items()
        }
        for os_label, per_os in results.items()
    }
    (args.out / "results.json").write_text(json.dumps(merged, indent=1, ensure_ascii=False), encoding="utf-8")
    print(summary)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
