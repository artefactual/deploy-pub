"""Print the ``rt/pipeline/decisions.py`` module from an Archivematica workflow.

Usage: python tools/extract_decisions.py path/to/workflow.json > rt/pipeline/decisions.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def description(value: object) -> str:
    if isinstance(value, dict):
        return str(value.get("en", ""))
    return str(value)


def main(path: Path) -> None:
    workflow = json.loads(path.read_text())
    links = workflow["links"]
    chains = workflow["chains"]
    decisions: dict[str, list[tuple[str, dict[str, str]]]] = {}
    for link_id, link in links.items():
        config = link["config"]
        model = config.get("@model")
        if model == "MicroServiceChainChoice":
            choices = {
                description(chains[chain_id]["description"]): chain_id
                for chain_id in config["chain_choices"]
                if chain_id in chains
            }
        elif model == "MicroServiceChoiceReplacementDic":
            choices = {
                description(replacement["description"]): replacement["id"]
                for replacement in config["replacements"]
            }
        else:
            continue
        name = description(link["description"])
        decisions.setdefault(name, []).append((link_id, choices))

    print('"""Decision points of the Archivematica workflow and the targets of their choices.')
    print()
    print("Generated by tools/extract_decisions.py from MCPServer/assets/workflow.json;")
    print("regenerate it when the workflow changes.")
    print('"""')
    print()
    print("from __future__ import annotations")
    print()
    print("from dataclasses import dataclass")
    print()
    print()
    print("@dataclass(frozen=True)")
    print("class Decision:")
    print("    link_id: str")
    print("    choices: dict[str, str]")
    print()
    print()
    print("DECISIONS: dict[str, tuple[Decision, ...]] = {")
    for name in sorted(decisions):
        print(f"    {name!r}: (")
        for link_id, choices in sorted(decisions[name]):
            print("        Decision(")
            print(f"            {link_id!r},")
            print("            {")
            for choice, target in choices.items():
                print(f"                {choice!r}: {target!r},")
            print("            },")
            print("        ),")
        print("    ),")
    print("}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
